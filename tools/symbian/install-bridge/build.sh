#!/bin/sh
set -eu
if [ "$#" -ne 3 ]; then
    echo 'Usage: sh tools/symbian/install-bridge/build.sh <symbian-platform-sdk> <S60v5-SDK-epoc32> <output-directory>' >&2
    exit 2
fi
sdk=$(cd "$1" && pwd)
legacy=$(cd "$2/release/armv5/lib" && pwd)
mkdir -p "$3"
output=$(cd "$3" && pwd)
src=$(cd "$(dirname "$0")" && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
cp "$src/bridge.cc" "$src/CMakeLists.txt" "$src/symbian.toml" "$src/../notes/start.S" "$work/"
node -e 'console.log(JSON.stringify({ sdk: process.argv[1] }))' "$sdk" > "$work/sdk-location.json"
proxies=
for library in euser efsrv apgrfx c32; do
    proxy="$work/$library"
    mkdir -p "$proxy"
    python3 "$src/../notes/ordinal_proxy.py" "$legacy/$library.dso" > "$proxy/exports.def"
    "$sdk/bin/symbian-native" proxy-sources --definition "$proxy/exports.def" --target-dll "$library.dll" --output "$proxy"
    "$sdk/bin/clang" --target=armv5t-none-eabi -c "$proxy/exports.S" -o "$proxy/exports.o"
    "$sdk/bin/ld.lld" -m armelf -shared --hash-style=sysv --build-id=none --soname="$library.dso" \
        --version-script="$proxy/exports.map" -T "$proxy/proxy.ld" "$proxy/exports.o" -o "$proxy/$library.dso"
    proxies="${proxies:+$proxies;}$proxy/$library.dso"
done
"$sdk/bin/cmake" -S "$work" -B "$work/build" -G Ninja \
    -DCMAKE_MAKE_PROGRAM="$sdk/bin/ninja" -DCMAKE_TOOLCHAIN_FILE="$sdk/cmake/symbian-arm.cmake" \
    -DSYMBIAN_TARGET_ARCH=armv6 -DCMAKE_BUILD_TYPE=Release \
    "-DAPPARC_PROXY=$work/apgrfx/apgrfx.dso" "-DCOMM_PROXY=$work/c32/c32.dso" "-DSYMBIAN_IMPORT_PROXIES=$proxies"
"$sdk/bin/cmake" --build "$work/build"
cp "$work/build/e32/v86_install.exe" "$output/"
"$sdk/bin/clang" --target=armv6-none-eabi -c "$src/bootstrap.S" -o "$work/bootstrap.o"
"$sdk/bin/ld.lld" --image-base=0 --oformat=binary -Ttext=0 -o "$output/bootstrap.bin" "$work/bootstrap.o"
node --input-type=module - "$output" > "$output/syborg_install_binary.js" <<'JS'
import { readFileSync } from "node:fs";
import { join } from "node:path";
const out = process.argv[2];
console.log("// Generated by tools/symbian/install-bridge/build.sh");
for(const [name, file] of [["INSTALL_BOOTSTRAP", "bootstrap.bin"], ["INSTALL_EXE", "v86_install.exe"]]) {
    const lines = readFileSync(join(out, file)).toString("base64").match(/.{1,100}/g);
    console.log(`\nexport const ${name} = [\n${lines.map(line => `    "${line}",`).join("\n")}\n].join("");`);
}
JS
