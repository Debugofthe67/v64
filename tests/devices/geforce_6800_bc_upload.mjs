#!/usr/bin/env node
import assert from "node:assert/strict";
import {NV40Render} from "../../src/graphics_adapters/geforce_6800/nv40_render.js";
import {d9wg_commands} from "../../src/graphics_adapters/vmware_svga/svga3d_d9wg.js";
import {OP,FIELD_LAYOUT} from "../../src/graphics_adapters/vmware_svga/d9wg_constants.js";
import {geforce_renderer_policy} from "../lib/geforce_renderer_policy.mjs";
let listener;const sent=[];
const vram = new Uint8Array(4096);
const device = {vram_size: vram.byteLength, vram: () => vram}, engine = {device, state: {device}};
const backend=new NV40Render(engine,{listen:fn=>{listener=fn;},post:m=>sent.push(m)});
assert.deepEqual(sent,[{type:"hello"}]);assert.equal(backend.bc_supported,false);
listener({type:"caps",textureCompressionBC:1});assert.equal(backend.bc_supported,false,"only an explicit enabled boolean grants BC");
listener({type:"caps",textureCompressionBC:true});assert.equal(backend.bc_supported,true);
backend.initialize();
const surface={dma:{instance:16},offset:0,pitch:16,width:8,height:8,depth:1,d3d:0x31545844,bpp:4,block:8,native_bc:true};
const pixels = vram.subarray(surface.offset, surface.offset + 32);
backend.target(surface,pixels,0);
assert.equal(backend.stats.resourceBytes,32,"GPU BC residency counts four blocks, not 64 expanded texels");
pixels[17] = 1;
backend.target(surface,pixels,0);
backend.target(surface,pixels,0); // Rebinding unchanged VRAM must not emit another update.
assert.equal(backend.stats.nativeBCUploads,2);assert.equal(backend.stats.nativeBCUploadBytes,48);
const commands=d9wg_commands(backend.writer.finish(1,0)).filter(c=>c.opcode===OP.UPDATE_TEXTURE);
const word=(c,name)=>c.view.getUint32(c.at+FIELD_LAYOUT.UpdateTexture.fields.find(f=>f[0]===name)[1],true);
assert.deepEqual(commands.map(c=>[word(c,"y"),word(c,"height"),word(c,"row_pitch"),word(c,"data_bytes")]),[[0,8,16,32],[4,4,16,16]],"partial updates retain complete block rows and texel-space extents");
const [initial, partial] = commands;
assert.equal(initial.view.getUint8(word(initial, "data_offset") + 17), 0);
assert.equal(partial.view.getUint8(word(partial, "data_offset") + 1), 1, "an in-place VRAM write updates the second block row");
const mips={...surface,offset:128,width:4,height:4,level_count:3,cube:true};
backend.target(mips,Array.from({length:18},()=>new Uint8Array(8)),0);
assert.equal(backend.stats.resourceBytes,32+6*3*8,"every cube mip tail occupies one complete block");
const updates=d9wg_commands(backend.writer.finish(2,0)).filter(c=>c.opcode===OP.UPDATE_TEXTURE);
assert.equal(updates.length,18);
assert.deepEqual(updates.slice(-3).map(c=>[word(c,"level"),word(c,"z"),word(c,"height"),word(c,"data_bytes")]),[[0,5,4,8],[1,5,2,8],[2,5,1,8]]);
backend.target({...surface,offset:256,width:3,height:2},new Uint8Array(8),0);
assert.equal(backend.stats.resourceBytes,32+6*3*8+24,"an NPOT base counts the executor's expanded RGBA storage");
listener({type:"lost",reason:"test"});assert.equal(backend.bc_supported,false,"lost devices cannot retain optional capabilities");
let incoming;const delivered=[],posts=[];
const channel={listen(fn){assert.equal(this,channel);incoming=fn;},post(message){posts.push(message);}};
assert.equal(geforce_renderer_policy(channel,"auto"),channel);
assert.equal(geforce_renderer_policy(channel,"cpu"),channel);
channel.listen(message=>delivered.push(message));
const caps={type:"caps",present:true,textureCompressionBC:true},write={type:"write",offset:4,bytes:new Uint8Array([17])},done={type:"done",seq:7};
incoming(caps);incoming(write);incoming(done);
assert.deepEqual(delivered[0],{...caps,textureCompressionBC:false});
assert.equal(caps.textureCompressionBC,true,"comparison policy never mutates the original host report");
assert.equal(delivered[1],write);assert.equal(delivered[2],done,"GPU data and completion retain their original objects and order");
const controlled=new NV40Render(engine,channel);incoming(caps);assert.equal(controlled.bc_supported,false);
controlled.reset();incoming(caps);assert.equal(controlled.bc_supported,false,"later hello/reset grants also retain the CPU baseline");
assert(posts.some(p=>p.type==="reset") && posts.filter(p=>p.type==="hello").length===2);
assert.throws(()=>geforce_renderer_policy(null,"cpu"),/real renderer/);
assert.throws(()=>geforce_renderer_policy(channel,"unknown"),/auto or cpu/);
console.log("PASS: checked BC capability, compressed residency, partial block rows, cube mip tails and NPOT expansion accounting");
