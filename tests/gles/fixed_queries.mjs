import assert from "node:assert/strict";
import { GLESHost } from "../../src/gles/gles_host.js";
import { client, fake_renderer, i32s, f32s } from "./lib.mjs";
const host = new GLESHost({width:640,height:960,dpi:326},fake_renderer());
const {call} = await client(host).connect();
const ctx=(await call("rcCreateContext",3,0,1)).ret;
await call("rcMakeCurrent",ctx,0,0);
const gl=(n,...a)=>call("gles1:"+n,...a);
const get=async(p,n=1)=>i32s((await gl("glGetFixedv",p,4*n)).outs[0]);
for(const [p,v] of [[0xba0,0x1700],[0xb54,0x1d01],[0xb65,0x800],[0xbc1,0x207],[0xbf0,0x1503],[0x84e0,0x84c0],[0x84e1,0x84c0],[0x807b,0x1406],[0xb45,0x405],[0xb74,0x201],[0xbe1,1]])
    assert.deepEqual(await get(p),[v],"fixed enum is unscaled: "+p.toString(16));
assert.deepEqual(await get(0xba3),[65536],"integer stack depth is scaled");
assert.deepEqual(await get(0xb00,4),[65536,65536,65536,65536]);
await gl("glTranslatex",32768,65536,0);
assert.equal((await get(0xba6,16))[12],32768);
await gl("glBindTexture",0xde1,1);
await gl("glTexParameterx",0xde1,0x84fe,229376);
assert.deepEqual(f32s((await gl("glGetTexParameterfv",0xde1,0x84fe,4)).outs[0]),[3.5]);
assert.deepEqual(i32s((await gl("glGetTexParameterxv",0xde1,0x84fe,4)).outs[0]),[229376]);
await gl("glTexParameterxv",0xde1,0x84fe,new Uint8Array(new Int32Array([163840]).buffer));
assert.deepEqual(f32s((await gl("glGetTexParameterfv",0xde1,0x84fe,4)).outs[0]),[2.5]);
await gl("glTexParameterx",0xde1,0x2801,0x2600);
assert.deepEqual(i32s((await gl("glGetTexParameterxv",0xde1,0x2801,4)).outs[0]),[0x2600]);
await gl("glTexParameterxv",0xde1,0x8b9d,new Uint8Array(new Int32Array([65536,0,131072,-131072]).buffer));
assert.deepEqual(i32s((await gl("glGetTexParameteriv",0xde1,0x8b9d,16)).outs[0]),[1,0,2,-2]);
assert.deepEqual(i32s((await gl("glGetTexParameterxv",0xde1,0x8b9d,16)).outs[0]),[65536,0,131072,-131072]);
await gl("glBindBuffer",0x8892,7);
await gl("glVertexPointerOffset",2,0x1406,16,8);
await gl("glClientActiveTexture",0x84c1);
await gl("glTexCoordPointerOffset",2,0x1406,16,0);
await gl("glBindBuffer",0x8893,7);
await gl("glDeleteBuffers",1,new Uint8Array(new Int32Array([7]).buffer));
for(const p of [0x8894,0x8895,0x8896,0x889a]) assert.deepEqual(i32s((await gl("glGetIntegerv",p,4)).outs[0]),[0]);
assert.equal((await gl("glGetError")).ret,0);
console.log("PASS: ES1 fixed enum/numeric conversions, texture forms and deleted array bindings");
