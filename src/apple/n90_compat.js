const ETHERNET_AT = 0x002B6200;
const LOOPBACK_ATTACH = 0x000E2BF2;
const ATTACH_CONTEXT = Uint8Array.of(0x20, 0x68, 0x00, 0x21, 0xFB, 0xF7, 0x3D, 0xF9, 0x02, 0x46, 0x5A, 0xB1);
const ATTACH_TRAMPOLINE = 0xFB05F1D3; // bl 0x802B6200

/** Give stock BSD interface enumeration a disconnected en0 with a local MAC. */
export function n90_ethernet(ram, kernel)
{
    if(kernel.uuid !== UUID) return;
    if(ETHERNET_AT + ETHERNET_ROUTINE.length > ram.length ||
        !ATTACH_CONTEXT.every((byte, index) => ram[LOOPBACK_ATTACH - 4 + index] === byte) ||
        !ram.subarray(ETHERNET_AT, ETHERNET_AT + ETHERNET_ROUTINE.length).every(byte => byte === 0))
        throw new Error("Unexpected 10B329 Ethernet initialization layout");

    ram.set(ETHERNET_ROUTINE, ETHERNET_AT);
    new DataView(ram.buffer, ram.byteOffset, ram.length).setUint32(LOOPBACK_ATTACH, ATTACH_TRAMPOLINE, true);
}
